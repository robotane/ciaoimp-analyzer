:- meta_predicate with_mod_syntax(goal).

default_prims('/home/robotane/Projects/stage/projet/src/ciaoimp-analyzer/tools/caslog_prep/hotmoka_caslog_prims.pl').

caslog_prep(Out) :-
    default_prims(P),
    caslog_prep(Out, P).

caslog_prep(Out, Prims) :-
    analyze(shfr),
    analyze(eterms),
    curr_file(_, M), !,
    read_prim_measures(Prims, PM),
    contract_clauses(Cls0),
    keep_preds(Cls0, Cls1),
    preds_of(Cls1, Preds),
    modes_measures(Preds, M, Info0),
    elim_all(Cls1, Info0, Cls, Unelim),
    complete_measures(Info0, Cls, PM, Info1),
    demote_counters(Info1, Cls, Info),
    open(Out, write, S),
    write(S, '% generated by caslog_prep.pl (CiaoPP shfr + eterms)\n'),
    write_entries(Preds, S),
    copy_file(Prims, S),
    write(S, '\n% contract: modes/measures derived from CiaoPP\n'),
    write_directives(Info, S),
    write(S, '\n% contract: expanded clauses\n'),
    write_clauses(Cls, S),
    report_unelim(Unelim, S),
    report_undefined(Cls, Preds, PM, S),
    close(S).

% ---------------------------------------------------------------------------
% Clauses of the contract (same enumeration as clean_print.pl)

contract_clauses(Cls) :-
    findall(cl(H, B, Dic),
            ( curr_file(_, M),
              pr_key_get(M, K),
              source_clause(_, clause(K, B0), Dic),
              rm(B0, B1),
              transform_clause_list([clause(K, B1)], M, L),
              member(clause(H, B2), L),
              strip(B2, B) ),
            Cls).

rm(B, B) :- var(B), !.
rm((A,Bs), (A1,B1)) :- !, rm(A, A1), rm(Bs, B1).
rm((A;Bs), (A1;B1)) :- !, rm(A, A1), rm(Bs, B1).
rm((A->Bs), (A1->B1)) :- !, rm(A, A1), rm(Bs, B1).
rm(L:_, L) :- !.
rm(L, L).

% remove the module qualification of goals (term_basic:=, hotmoka:load, ...)
strip(B, B) :- var(B), !.
strip((A,Bs), (A1,B1)) :- !, strip(A, A1), strip(Bs, B1).
strip((A;Bs), (A1;B1)) :- !, strip(A, A1), strip(Bs, B1).
strip((A->Bs), (A1->B1)) :- !, strip(A, A1), strip(Bs, B1).
strip(\+ A, \+ A1) :- !, strip(A, A1).
strip(M:G, G1) :- atom(M), !, strip(G, G1).
strip(require(C), G1) :- !, req_cond(C, C1), strip(C1, G1).
strip(require(C, _), G1) :- !, req_cond(C, C1), strip(C1, G1).
strip(G, G).

% require(Cond[, Message]) is unfolded into Cond by hotmoka_tr.pl at compile
% time; a require left in a clause (a contract loaded without the hotmoka_gas
% package) is unfolded the same way, so that it costs no CasLog step of its own.
req_cond(C, C) :- var(C), !.
req_cond((A ; B), (A -> true ; B1)) :- !, req_cond(B, B1).
req_cond(C, C).

% regtype/prop predicates, goal/N and goal_chain/N are not part of the analysis
keep_preds([], []).
keep_preds([cl(H,B,D)|Cs], Out) :-
    functor(H, F, A),
    ( skip_pred(F, A) -> Out = Out1 ; Out = [cl(H,B,D)|Out1] ),
    keep_preds(Cs, Out1).

skip_pred(F, A) :-
    ( pgm_regtype(G0, _), functor(G0, F0, A), module_split(F0, _, F) ), !.
skip_pred(F, _) :- test_name(F).

test_name(goal).
test_name(goal_chain).
test_name(F) :- atom_concat(goal, R, F), atom_concat('$', _, R).
test_name(F) :- atom_concat(goal_chain, R, F), atom_concat('$', _, R).

% ---------------------------------------------------------------------------
% Elimination of unifications  X = Y  by binding

elim_all([], _, [], []).
elim_all([cl(H,B0,D)|Cs], Info, [cl(H,B,D)|Os], Un) :-
    conj_list(B0, L0),
    functor(H, F, A),
    ( member(info(F/A, Modes, _), Info) -> true ; Modes = [] ),
    elim_goals(L0, H, Modes, [], no, L, U),
    conj_list_(L, B),
    ( U == [] -> Un = Un1 ; Un = [F/A-U|Un1] ),
    elim_all(Cs, Info, Os, Un1).

conj_list(B, [B]) :- var(B), !.
conj_list((A,Bs), [A|L]) :- !, conj_list(Bs, L).
conj_list(true, []) :- !.
conj_list(G, [G]).

conj_list_([], true) :- !.
conj_list_([G], G) :- !.
conj_list_([G|Gs], (G,B)) :- conj_list_(Gs, B).

elim_goals([], _, _, _, _, [], []).
elim_goals([G|Gs], H, Mo, Prev, Cut, Out, Un) :-
    ( G = (X = Y), can_elim(X, Y, H, Mo, Prev, Cut) ->
        X = Y,
        elim_goals(Gs, H, Mo, Prev, Cut, Out, Un)
    ; ( G = (_ = _) -> Un = [G|Un1] ; Un = Un1 ),
      ( G == (!) -> Cut1 = yes ; Cut1 = Cut ),
      Out = [G|Out1],
      elim_goals(Gs, H, Mo, [G|Prev], Cut1, Out1, Un1)
    ).

% X = Y is eliminated by binding when one side is a variable V and
%  - it is the first goal (it is then the head unification), or
%  - V does not occur in the previous goals and either V is local to the
%    clause or V is a head argument that is free at call (mode -), or
%  - V occurs in the previous goals, but no cut precedes and no previous
%    goal compares it (==, \==): the unification only moves earlier.
can_elim(X, Y, H, Mo, Prev, Cut) :-
    \+ occurs_in(X, Y), \+ occurs_in(Y, X),
    ( var(X) ; var(Y) ; \+ \+ X = Y ),
    ( Prev == [] -> true
    ; Cut == no, nonvar(X), nonvar(Y) -> true
    ; ( elim_var(Y, H, Mo, Prev, Cut) ; elim_var(X, H, Mo, Prev, Cut) ) ), !.

elim_var(V, H, Mo, Prev, Cut) :-
    var(V),
    \+ compared(V, Prev),
    (   Cut == no
    ;   \+ occurs_in(V, Prev),
        ( \+ occurs_in(V, H) ; free_head_var(V, H, Mo) )
    ), !.

% V only occurs in the head as whole arguments, all of them free at call
free_head_var(V, H, Mo) :-
    functor(H, _, A),
    \+ ( between(1, A, I), arg(I, H, Arg), occurs_in(V, Arg),
         \+ ( Arg == V, nth_el(I, Mo, (-)) ) ).

occurs_in(V, T) :- var(V), term_variables(T, Vs), member(W, Vs), W == V, !.

compared(V, Prev) :-
    member(G, Prev),
    ( G = (A == B) ; G = (A \== B) ),
    ( occurs_in(V, A) ; occurs_in(V, B) ), !.

report_unelim([], _) :- !.
report_unelim(Un, S) :-
    write(S, '\n% unifications kept (CasLog does not know =/2):\n'),
    ( member(P-Gs, Un),
      write(S, '%   '), writeq(S, P), write(S, ' : '), length(Gs, N), write(S, N), nl(S),
      fail ; true ).

% ---------------------------------------------------------------------------
% Modes and measures

preds_of(Cls, Preds) :-
    preds_of_(Cls, [], Rev), reverse(Rev, Preds).
preds_of_([], Acc, Acc).
preds_of_([cl(H,_,_)|Cs], Acc, Out) :-
    functor(H, F, A),
    ( member(F/A, Acc) -> Acc1 = Acc ; Acc1 = [F/A|Acc] ),
    preds_of_(Cs, Acc1, Out).

% info(F/A, Modes, Measures)
modes_measures([], _, []).
modes_measures([F/A|Ps], M, [info(F/A, Modes, Ms)|Is]) :-
    atom_concat(M, ':', MC), atom_concat(MC, F, Fq),
    functor(G, Fq, A),
    get_predkey(Fq, A, K),
    arg_modes(K, G, A, Modes),
    ( get_info(regtypes, pred, K, G, (C, S)),
      type2measure(G, C, Mc), type2measure(G, S, Ms0) -> true
    ; length(Mc, A), length(Ms0, A), all(void, Mc), all(void, Ms0) ),
    pick_measures(Modes, Mc, Ms0, Ms),
    modes_measures(Ps, M, Is).

all(_, []).
all(X, [X|T]) :- all(X, T).

pick_measures([], [], [], []).
pick_measures([Mo|Mos], [C|Cs], [S|Ss], [M|Ms]) :-
    norm(C, C1), norm(S, S1),
    ( Mo == (+) -> first_known(C1, S1, M) ; first_known(S1, C1, M) ),
    pick_measures(Mos, Cs, Ss, Ms).

norm(length, length) :- !.
norm(int, int) :- !.
norm(_, void).

first_known(void, X, X) :- !.
first_known(X, _, X).

% shfr: argument status in every call version (get_completes + asub_to_info)
arg_modes(K, G, A, Modes) :-
    ( get_completes(K, G, shfr, Cs) -> true ; Cs = [] ),
    findall(St-I, ( member(complete(G1, Call, _, _, _), Cs),
                    varset(G1, Vs),
                    asub_to_info(shfr, Call, Vs, Info, _),
                    between(1, A, I),
                    arg(I, G1, Arg),
                    status(Arg, Info, St) ), Sts),
    decide_modes(1, A, Sts, Modes).

% a constant actual argument (call coming from goal/1, the test) is no evidence
status(Arg, _, unknown) :- nonvar(Arg), !.
status(Arg, Info, St) :-
    member(P, Info),
    P =.. [Pr, X],
    prop_name(Pr, Nm),
    ( Nm == var, X == Arg, St = free
    ; Nm == ground, memq(Arg, X), St = ground ), !.
status(_, _, unknown).

prop_name(Pr, Nm) :- module_split(Pr, _, Nm).

memq(X, [Y|T]) :- ( X == Y -> true ; memq(X, T) ).

decide_modes(I, A, _, []) :- I > A, !.
decide_modes(I, A, Sts, [Mo|Ms]) :-
    ( member(free-I, Sts) -> F = yes ; F = no ),
    % free in some call version: output (a ground version of the same argument
    % comes from the constants of goal/1, e.g. Ok = 1; the entry says var)
    ( F == yes -> Mo = (-) ; Mo = (+) ),
    I1 is I + 1,
    decide_modes(I1, A, Sts, Ms).

between(L, H, L) :- L =< H.
between(L, H, X) :- L < H, L1 is L + 1, between(L1, H, X).

% void measures completed from the clauses (fixpoint)
complete_measures(Info0, Cls, PM, Info) :-
    improve(Info0, Cls, PM, Info1, Changed),
    ( Changed == yes -> complete_measures(Info1, Cls, PM, Info) ; Info = Info1 ).

improve([], _, _, [], no).
improve([info(P,Mo,Ms0)|Is], Cls, PM, [info(P,Mo,Ms)|Os], Ch) :-
    P = F/A, functor(Hd, F, A),
    improve_args(Ms0, 1, Hd, [info(P,Mo,Ms0)|Is], Cls, PM, Ms),
    improve(Is, Cls, PM, Os, Ch1),
    ( Ms == Ms0 -> Ch = Ch1 ; Ch = yes ).

improve_args([], _, _, _, _, _, []).
improve_args([M0|Ms0], I, Hd, Info, Cls, PM, [M|Ms]) :-
    ( M0 == void, inferred_measure(Hd, I, Info, Cls, PM, M1) -> M = M1 ; M = M0 ),
    I1 is I + 1,
    improve_args(Ms0, I1, Hd, Info, Cls, PM, Ms).

inferred_measure(Hd, I, Info, Cls, PM, M) :-
    functor(Hd, F, A),
    member(cl(H, B, _), Cls), functor(H, F, A),
    arg(I, H, X),
    ( nonvar(X) -> struct_measure(X, M)
    ; body_goal(B, L), functor(L, LF, LA), LF/LA \== F/A,
      callee_measures(LF/LA, Info, PM, CMs),
      between(1, LA, J), arg(J, L, Y), Y == X, nth_el(J, CMs, M), M \== void ), !.

struct_measure([], length).
struct_measure([_|_], length).
struct_measure(N, int) :- integer(N).

nth_el(1, [X|_], X) :- !.
nth_el(N, [_|T], X) :- N > 1, N1 is N - 1, nth_el(N1, T, X).

callee_measures(P, _, PM, Ms) :- member(pm(P, Ms), PM), !.
callee_measures(P, Info, _, Ms) :- member(info(P, _, Ms), Info).

body_goal(B, _) :- var(B), !, fail.
body_goal((A,B), G) :- !, ( body_goal(A, G) ; body_goal(B, G) ).
body_goal((A;B), G) :- !, ( body_goal(A, G) ; body_goal(B, G) ).
body_goal((A->B), G) :- !, ( body_goal(A, G) ; body_goal(B, G) ).
body_goal(G, G) :- nonvar(G).

% An int argument that a recursive call replaces by V is, with V an
% arithmetic result computed from it (W is I+1), is a counter: its size has no
% bound CasLog can use (the recursion is on a list), so its measure is void.
demote_counters([], _, []).
demote_counters([info(P,Mo,Ms0)|Is], Cls, [info(P,Mo,Ms)|Os]) :-
    P = F/A,
    demote_args(Ms0, 1, F, A, Cls, Ms),
    demote_counters(Is, Cls, Os).

demote_args([], _, _, _, _, []).
demote_args([M0|Ms0], I, F, A, Cls, [M|Ms]) :-
    ( M0 == int, counter_arg(I, F, A, Cls) -> M = void ; M = M0 ),
    I1 is I + 1,
    demote_args(Ms0, I1, F, A, Cls, Ms).

counter_arg(I, F, A, Cls) :-
    member(cl(H, B, _), Cls), functor(H, F, A),
    arg(I, H, X), var(X),
    body_goal(B, Call), functor(Call, F, A),
    arg(I, Call, W), var(W),
    body_goal(B, (W0 is E)), W0 == W,
    occurs_in(X, E), !.

% measures of the primitives, read from the primitives file
read_prim_measures(File, PM) :-
    open(File, read, S),
    read_terms(S, PM),
    close(S).
read_terms(S, PM) :-
    read(S, T),
    ( T == end_of_file -> PM = []
    ; T = (:- measure(F/A, Ms)) -> PM = [pm(F/A, Ms)|PM1], read_terms(S, PM1)
    ; read_terms(S, PM) ).

% ---------------------------------------------------------------------------
% Output

write_entries(Preds, S) :-
    ( entry_assertion(G, _, _), functor(G, F, A), module_split(F, _, F0),
      member(F0/A, Preds),
      write(S, '% entry: '), writeq(S, F0/A), nl(S), fail ; true ).

write_directives([], _).
write_directives([info(F/A, Mo, Ms)|Is], S) :-
    write(S, ':- mode('), writeq(S, F/A), write(S, ', '), write(S, Mo), write(S, ').\n'),
    write(S, ':- measure('), writeq(S, F/A), write(S, ', '), write(S, Ms), write(S, ').\n'),
    write_directives(Is, S).

write_clauses(Cls, S) :-
    with_mod_syntax(write_clauses_(Cls, S)).
write_clauses_([], _).
write_clauses_([cl(H,B,D)|Cs], S) :-
    pretty_print(S, [clause(H, B)], [], [D]),
    write_clauses_(Cs, S).

copy_file(F, S) :-
    open(F, read, In),
    copy_stream(In, S),
    close(In).
copy_stream(In, S) :-
    get_code(In, C),
    ( C = -1 -> true ; put_code(S, C), copy_stream(In, S) ).

% called predicates that are neither defined nor primitives nor builtins
report_undefined(Cls, Preds, PM, S) :-
    findall(F/A, ( member(cl(_,B,_), Cls), body_goal(B, G), functor(G, F, A),
                   \+ member(F/A, Preds), \+ member(pm(F/A,_), PM),
                   \+ builtin_ok(F/A) ), L0),
    sort(L0, L),
    ( L == [] -> true
    ; write(S, '\n% undefined predicates: '), writeq(S, L), nl(S) ).

builtin_ok(F/A) :- member(F/A, [(is)/2, (<)/2, (>)/2, (=<)/2, (>=)/2, (=:=)/2,
    (=\=)/2, (==)/2, (\==)/2, (=)/2, (!)/0, true/0, fail/0]).
