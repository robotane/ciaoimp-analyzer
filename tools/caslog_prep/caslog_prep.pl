% caslog_prep: Hotmoka contract (imperative Ciao DSL) -> file ready for CasLog.
%
% Use from "ciaopp -T" (see README.md):
%     use_module('.../caslog_prep.pl').
%     module('/abs/contract.pl').
%     caslog_prep('/abs/out_caslog.pl').
%     halt.
%
% caslog_prep/1 runs analyze(shfr) and analyze(eterms) on the loaded module,
% then writes into the output file:
%   1. the fixed primitives (hotmoka_caslog_prims.pl, hand-written mode/measure)
%   2. mode/measure of every predicate of the contract, derived from CiaoPP:
%        mode    : shfr call patterns of all the versions (get_completes/4,
%                  asub_to_info/5): '-' if the argument is free in the calls,
%                  '+' if bound/ground
%        measure : eterms types (get_info(regtypes,...) + type2measure/3, the
%                  CiaoPP translation types -> measures): length for lists,
%                  int for numbers, void otherwise. A still-void measure is
%                  completed from the structure of the clauses (head argument
%                  that is a list/number, or variable passed to a callee whose
%                  measure is known).
%   3. the expanded clauses (as clean_print.pl), in which the unifications
%      X = Y that can be done at compile time are eliminated by binding.
:- module(caslog_prep, [caslog_prep/1, caslog_prep/2], []).

